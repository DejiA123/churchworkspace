#!/usr/bin/env node
/*
 * Builds src/renderer/wordbook-english.js — the everyday English words and
 * common personal names that the Word Book's BUILT-IN Bible names are never
 * allowed to replace (see "KNOWN WORDS" in src/renderer/wordbook.js).
 *
 * Sources (all free to redistribute; their notices are kept in the output):
 *   - SCOWL, levels 10–60 (a standard spell checker's list plus the next two
 *     rarer levels), every English spelling: npm `wordlist-english` (MIT; SCOWL © Kevin Atkinson,
 *     permissive licence, with public-domain Moby and Kelk word lists).
 *   - First names: npm `@stdlib/datasets-male-first-names-en` and
 *     `-female-first-names-en` (Moby Words II, public domain), and the 1990 US
 *     Census first names from npm `node-random-name` (US Government work,
 *     public domain).
 *   - Surnames: the 5,000 most common of the 1990 US Census list, from that
 *     same package.
 *   - Every word of the King James Bible (public domain), so a preacher
 *     reading Chronicles keeps "Shallum", "Pharez" and "Abiram" instead of
 *     getting "Shalom", "Pharisee" and "Abram" — and "predestinated" stays.
 *     Pass the Project Gutenberg text as KJV=<path>.
 *   - The 20,000 commonest words of written English (countries, cities,
 *     nationalities, "dont"…), FREQ=<path>, one word per line in frequency
 *     order (made with wordfreq's top_n_list('en', …); the misspellings the
 *     book exists to fix are not among even the top 100,000).
 *   - scripts/wordbook-english-extra.txt: real words, places and names the
 *     lists above miss but the built-in names were found pulling ("Ibadan",
 *     "Ghanaian", "Syrian", "curated"), each checked by hand. Found by running
 *     the book over the 100,000 commonest words of written English
 *     (test/wordbook.test.js keeps a sample of them as checks).
 *
 * Usage (from a folder where those four packages were `npm pack`ed and
 * unpacked, each into its own directory):
 *   node scripts/build-wordbook-english.js <wordlist-english dir> <male names dir> \
 *        <female names dir> <node-random-name dir>
 */
const fs = require('fs');
const path = require('path');

const [scowl, male, female, census] = process.argv.slice(2);
if (!census) { console.error('usage: build-wordbook-english.js <wordlist-english> <male> <female> <node-random-name>'); process.exit(2); }

const LEVELS = [10, 20, 35, 40, 50, 55, 60];
const DIALECTS = ['english', 'american', 'british', 'canadian', 'australian'];
const SURNAMES = 5000;

const words = new Set();
const add = (w) => {
  const n = String(w).toLowerCase().replace(/[’]/g, "'");
  // the Word Book never re-spells a word under four letters, so those need no entry
  if (/^\p{Ll}[\p{Ll}']*$/u.test(n) && n.replace(/'/g, '').length >= 4) words.add(n);
};
for (const d of DIALECTS) for (const l of LEVELS) {
  const f = path.join(scowl, `${d}-words-${l}.json`);
  if (fs.existsSync(f)) for (const w of JSON.parse(fs.readFileSync(f, 'utf8'))) if (!/[A-Z]/.test(w)) add(w);
}
const scowlCount = words.size;
for (const dir of [male, female]) for (const w of fs.readFileSync(path.join(dir, 'data', 'names.txt'), 'utf8').split(/\s+/)) if (w) add(w);
const C = require(path.resolve(census, 'lib', 'names.js'));
for (const w of C.first_male.concat(C.first_female)) add(w);
for (const w of C.last.slice(0, SURNAMES)) add(w);
if (process.env.KJV) {
  const kjv = fs.readFileSync(process.env.KJV, 'utf8');
  for (const w of kjv.split(/[^A-Za-z']+/)) add(w.replace(/^'+|'+$/g, '').replace(/'s$/i, ''));
} else console.error('warning: no KJV=<path> given, the Bible words are left out');
if (process.env.FREQ) {
  const freq = fs.readFileSync(process.env.FREQ, 'utf8').split('\n').filter(Boolean);
  for (const w of freq.slice(0, +(process.env.FREQ_TOP || 20000))) add(w);
} else console.error('warning: no FREQ=<path> given, the commonest-words list is left out');
const EXTRA = path.join(__dirname, 'wordbook-english-extra.txt');
if (fs.existsSync(EXTRA)) for (const line of fs.readFileSync(EXTRA, 'utf8').split('\n')) {
  const w = line.replace(/#.*/, '').trim();
  if (w) add(w);
}

/* Front-coded: sorted, each word as one character saying how many letters it
 * shares with the word before (0-9, then a-z for 10-35), then the rest of it. */
const sorted = [...words].sort();
const digit = (k) => (k < 10 ? String(k) : String.fromCharCode(87 + k));
let prev = '';
const out = sorted.map((w) => {
  let k = 0;
  while (k < 35 && k < w.length && k < prev.length && w[k] === prev[k]) k++;
  prev = w;
  return digit(k) + w.slice(k);
}).join(' ');

const file = `/*
 * GENERATED by scripts/build-wordbook-english.js — do not edit by hand.
 *
 * ${sorted.length} everyday English words and common personal names (${scowlCount} from SCOWL,
 * the rest first names, surnames, every word of the King James Bible, the
 * 20,000 commonest written words, and the hand-checked places and words in
 * scripts/wordbook-english-extra.txt). The Word Book's BUILT-IN Bible names may
 * never replace one of these: a heard word that is real English, or a real
 * person's name, is not a mishearing of "Pilate" or "Simeon" — it is what was
 * said. See "KNOWN WORDS" in wordbook.js.
 *
 * Front-coded: each entry is one character for the number of letters it shares
 * with the entry before (0-9, then a-z for 10-35), then the rest of the word.
 *
 * SCOWL: Copyright 2000-2016 by Kevin Atkinson. Permission to use, copy,
 * modify, distribute and sell these word lists, the associated scripts, the
 * output created from the scripts, and its documentation for any purpose is
 * hereby granted without fee, provided that the above copyright notice appears
 * in all copies and that both that copyright notice and this permission notice
 * appear in supporting documentation. Kevin Atkinson makes no representations
 * about the suitability of this array for any purpose. It is provided "as is"
 * without express or implied warranty. (SCOWL also includes the Moby Words II
 * and Brian Kelk word lists, both public domain.)
 * Names: Moby Words II (public domain); 1990 US Census (public domain).
 * King James Bible: public domain (Project Gutenberg text).
 */
(function (data) {
  if (typeof module === 'object' && module.exports) module.exports = data;
  if (typeof window !== 'undefined') window.WordBookEnglish = data;
}(${JSON.stringify(out)}));
`;
const dest = path.join(__dirname, '..', 'src', 'renderer', 'wordbook-english.js');
fs.writeFileSync(dest, file);
console.log(`${sorted.length} words (${scowlCount} SCOWL) -> ${dest} (${(file.length / 1024).toFixed(0)} KB)`);
